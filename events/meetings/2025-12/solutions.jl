G = SL(2,4)
H = alternating_group(5)

is_isomorphic(G, H)

isomorphism(G, H)

S, = sylow_subgroup(G, 2)
N, = normalizer(G, S)
act = right_coset_action(G, N)
is_bijective(act)

U = image(act)[1]
order(U)
degree(U)
is_natural_alternating_group(U)
